package ru.mifi.practice.entity;

/**
 * Насекомое. Общий тип для мух, тараканов и сколопендр — игрок бьёт их одинаково,
 * а отличаются они поведением и тем, каким предметом их можно достать.
 */
public interface Bug extends Dynamic {

    /**
     * Летает ли насекомое. От этого зависит, каким предметом до него можно достать:
     * тапком — до бегающих, мухобойкой — до летающих.
     */
    boolean flying();
}
